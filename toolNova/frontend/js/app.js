function translate(key, lang) {
    return translations[lang] && translations[lang][key] ? translations[lang][key] : key;
}

function applyLanguage(lang) {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerText = translate(key, lang);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = translate(key, lang);
    });

    renderTools(document.querySelector('.filter-btn.active')?.dataset.cat || 'all', document.getElementById('toolSearch').value);
}

function renderTools(filter = 'all', search = '') {
    const grid = document.getElementById('toolGrid');
    if(!grid) return;

    const lang = localStorage.getItem('lang') || 'en';
    grid.innerHTML = '';

    const filtered = tools.filter(t => {
        const name = translate(t.name, lang).toLowerCase();
        const desc = translate(t.desc, lang).toLowerCase();
        return (filter === 'all' || t.cat === filter) &&
               (name.includes(search.toLowerCase()) || desc.includes(search.toLowerCase()));
    });

    filtered.forEach(t => {
        const config = toolIcons[t.id] || { icon: 'tool', color: 'linear-gradient(135deg, #ccc, #999)' };
        const card = document.createElement('div');
        card.className = 'tool-card';
        card.style.cssText = `
            background: rgba(255, 255, 255, 0.05);
            border: 1px solid rgba(255, 255, 255, 0.1);
            border-radius: 24px;
            padding: 32px;
            text-align: center;
            transition: all 0.4s cubic-bezier(0.4, 0, 0.2, 1);
            display: flex;
            flex-direction: column;
            align-items: center;
            backdrop-filter: blur(10px);
            cursor: pointer;
            box-shadow: 0 4px 15px rgba(0,0,0,0.1);
        `;

        card.innerHTML = `
            <div style="
                width: 64px;
                height: 64px;
                border-radius: 18px;
                background: ${config.color};
                display: flex;
                align-items: center;
                justify-content: center;
                margin-bottom: 20px;
                color: white;
                box-shadow: 0 8px 20px rgba(0,0,0,0.2);
            ">
                <i data-lucide="${config.icon}" style="width: 32px; height: 32px;"></i>
            </div>
            <h3 style="font-size: 1.3rem; font-weight: 700; margin-bottom: 12px; color: white;">${translate(t.name, lang)}</h3>
            <p style="font-size: 0.95rem; color: #cbd5e1; margin-bottom: 24px; line-height: 1.5;">${translate(t.desc, lang)}</p>
            <a href="${t.link}" class="btn btn-small" style="
                width: 100%;
                justify-content: center;
                border-radius: 100px;
                font-weight: 600;
                background: rgba(255,255,255,0.1);
                color: white;
                border: 1px solid rgba(255,255,255,0.2);
                text-decoration: none;
                padding: 10px;
                transition: 0.3s;
            ">Open Tool</a>
        `;

        card.onmouseenter = () => {
            card.style.transform = 'translateY(-10px)';
            card.style.borderColor = 'var(--primary-color)';
            card.style.boxShadow = '0 20px 40px rgba(79, 70, 229, 0.3)';
        };
        card.onmouseleave = () => {
            card.style.transform = 'translateY(0)';
            card.style.borderColor = 'rgba(255, 255, 255, 0.1)';
            card.style.boxShadow = '0 4px 15px rgba(0,0,0,0.1)';
        };

        grid.appendChild(card);
    });

    if (window.lucide) {
        lucide.createIcons();
    }
}

document.addEventListener('DOMContentLoaded', () => {
    const searchInput = document.getElementById('toolSearch');
    const filters = document.querySelectorAll('.filter-btn');
    const langSwitch = document.getElementById('langSwitch');

    if (langSwitch) {
        langSwitch.value = localStorage.getItem('lang') || 'en';
        langSwitch.addEventListener('change', (e) => {
            localStorage.setItem('lang', e.target.value);
            applyLanguage(e.target.value);
        });
    }

    if(searchInput) {
        searchInput.oninput = (e) => renderTools(document.querySelector('.//filter-btn.active')?.dataset.cat || 'all', e.target.value);
    }

    if(filters) {
        filters.forEach(btn => {
            btn.onclick = () => {
                filters.forEach(b => b.classList.remove('active'));
                btn.classList.add('active');
                renderTools(btn.dataset.cat, searchInput ? searchInput.value : '');
            };
        });
    }

    applyLanguage(localStorage.getItem('lang') || 'en');
});
